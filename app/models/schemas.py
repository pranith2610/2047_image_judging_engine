# --- REFERENCE PROFILE ---

class ReferenceProfile(BaseModel):
    """
    Structured Reference Profile generated from the original competition image.
    This serves as the single source of truth for all participant evaluations.
    """
    image_id: str
    filename: str
    dimensions: Tuple[int, int]
    status: AnalysisStatus = AnalysisStatus.COMPLETED
    error_message: Optional[str] = None

    # A. Main Subject
    main_subject: Optional[ObjectFeature] = None

    # B. Secondary Subjects
    secondary_subjects: List[ObjectFeature] = Field(default_factory=list)

    # C. All Meaningful Objects
    objects: List[ObjectFeature] = Field(default_factory=list)

    # D. Scene / Environment
    scene: SceneFeature = Field(default_factory=SceneFeature)

    # E. Composition
    composition: CompositionFeature = Field(default_factory=CompositionFeature)

    # F. Colors
    colors: ColorFeature = Field(default_factory=ColorFeature)

    # G. Lighting
    lighting: LightingFeature = Field(default_factory=LightingFeature)

    # H. Visual Details
    details: DetailFeature = Field(default_factory=DetailFeature)

    # I. Image Structure
    structure: StructureFeature = Field(default_factory=StructureFeature)

    # Visual Embedding (CLIP)
    visual_embedding: Optional[VisualEmbedding] = None

    # Semantic Summary
    semantic_summary: str = ""

    # Detected Semantic Features
    detected_features: Dict[str, float] = Field(default_factory=dict)

    # Compatibility properties for existing engine consumers
    @property
    def main_subjects(self) -> List[ObjectFeature]:
        return [self.main_subject] if self.main_subject else []

    @property
    def dominant_colors(self) -> ColorFeature:
        return self.colors

    @property
    def visual_details(self) -> DetailFeature:
        return self.details

    @property
    def scene_environment(self) -> str:
        return self.scene.scene_context

    @property
    def background(self) -> str:
        return self.scene.background

    @property
    def foreground(self) -> str:
        return self.scene.foreground

    @property
    def spatial_relationships(self) -> List[str]:
        return [f"{k}: {v}" for k, v in self.composition.spatial_relationships.items()]


