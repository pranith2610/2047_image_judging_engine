"""
Pydantic schemas and data structures for THE 2047 judging engine.
Includes full Image Analysis Layer data models:
ReferenceProfile, ParticipantProfile, VisualEmbedding, ObjectFeature,
CompositionFeature, ColorFeature, LightingFeature, SceneFeature,
DetailFeature, StructureFeature, ComparisonResult, ScoringResult.
"""
from typing import List, Dict, Optional, Tuple, Any
from pydantic import BaseModel, Field
from app.models.enums import ImportanceLevel, SpatialQuadrant, AnalysisStatus, SceneType, ObjectMatchStatus


class BoundingBox(BaseModel):
    """Normalized bounding box coordinates (0.0 to 1.0)."""
    xmin: float = Field(0.0, ge=0.0, le=1.0)
    ymin: float = Field(0.0, ge=0.0, le=1.0)
    xmax: float = Field(1.0, ge=0.0, le=1.0)
    ymax: float = Field(1.0, ge=0.0, le=1.0)


class DominantColor(BaseModel):
    """Color representation with RGB, HEX and coverage percentage."""
    hex_code: str
    rgb: Tuple[int, int, int]
    percentage: float = Field(..., ge=0.0, le=100.0)
    color_name: Optional[str] = None


class VisualEmbedding(BaseModel):
    """Visual feature embedding generated by vision models."""
    model_name: str = "THE-2047-ViT-SpatialEmbedding"
    dimension: int = 512
    embedding: List[float] = Field(default_factory=list)
    is_normalized: bool = True


class ObjectFeature(BaseModel):
    """
    An identified visual object or element with location and 30-second memory importance.
    """
    name: str
    category: str = "general"
    importance: ImportanceLevel = ImportanceLevel.MEDIUM
    location: str = "center"  # e.g. "center-left", "upper-right", "lower-center"
    relative_size: float = Field(0.0, ge=0.0, le=100.0, description="Approximate area percentage")
    confidence: float = Field(1.0, ge=0.0, le=1.0)
    bounding_box: Optional[BoundingBox] = None
    quadrant: Optional[SpatialQuadrant] = None
    memory_prominence: str = "Salient visual subject"
    notes: Optional[str] = None
    match_status: Optional[ObjectMatchStatus] = None


# Backward-compatible alias
VisualElement = ObjectFeature


